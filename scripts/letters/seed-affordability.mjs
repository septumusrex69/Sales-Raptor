/**
 * PUT THE TWO AFFORDABILITY ASSESSMENTS INTO A DATABASE.
 *
 * Four rows: a form and a covering email, for a person and for a company. The documents themselves
 * are built by affordability.mjs and live in letters.json, which is the source of truth; this only
 * carries them across.
 *
 * A SEPARATE FILE FROM seed-aod.mjs ON PURPOSE. That one carries a long note about adoption and a
 * correction to twelve notices already in the database, neither of which applies here -- these four
 * rows have never existed, so there is nothing to adopt and nothing to correct. Folded together,
 * the file would read as though the AoD's history were these documents' history too.
 *
 * UPSERT ON seed_key, which is unique, so a second run overwrites the four rows rather than making
 * four more. No deletes: seed-aod.mjs records why that matters -- every DELETE sent through the
 * session that wrote it hung and rolled back, and a seed nobody can run is a seed that does not
 * exist.
 *
 *   SUPABASE_URL=https://<ref>.supabase.co \
 *   SUPABASE_SERVICE_ROLE_KEY=<key> \
 *   node scripts/letters/seed-affordability.mjs
 *
 *   node scripts/letters/seed-affordability.mjs --sql > scripts/letters/seed-affordability.sql
 *
 * The service role key is read from the environment and never written anywhere -- not into a file,
 * not into the repository, which is public.
 */
import { readFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { covering } from './affordability.mjs'

const letters = JSON.parse(readFileSync(new URL('./letters.json', import.meta.url), 'utf8'))

/**
 * The four rows.
 *
 * `seed_key` IS WHAT MAKES ANY OF THIS WORK TWICE, and here it is load-bearing twice over:
 * signingRules.SIGNABLE_SEED_KEYS names `letter-affordability-individual` and
 * `letter-affordability-company`, and SigningPanel.DOCUMENTS names the two covering emails. A row
 * seeded without them is a form the firm can see in the Library and cannot send for signature.
 *
 * `format = 'document'` because the body is letterDocument JSON. seed-aod.mjs records at length
 * what writing 'text' here costs: the Attach control filters on this column, so the firm would see
 * nothing in it.
 *
 * AND THE COVERING EMAILS ARE NOT IN byHand.BY_HAND_SEED_KEYS, deliberately, for the same reason
 * the acknowledgement's are not: the message is only half a message without the 43-character token
 * made at the moment of sending, and a template saved weeks earlier cannot carry one. It goes out
 * from the Signing panel, which appends the button.
 */
const rows = ['individual', 'company'].flatMap((kind) => {
  const who = kind === 'company' ? 'company' : 'individual'
  return [
    {
      scope: 'collections',
      kind: 'letter',
      name: `Affordability assessment (${who})`,
      subject: null,
      format: 'document',
      body: JSON.stringify(letters[`letter-affordability-${kind}`]),
      seed_key: `letter-affordability-${kind}`,
      audience: who,
    },
    {
      scope: 'collections',
      kind: 'email',
      name: `Affordability assessment — covering email (${who})`,
      /* NAMES THE ACCOUNT, because this arrives in an inbox beside the firm's other mail and the
         debtor has to be able to tell which account it is about before opening it. */
      subject: 'Affordability assessment — account {{account_number}}',
      format: 'text',
      body: covering(kind),
      seed_key: `email-affordability-${kind}`,
      audience: who,
    },
  ]
})

const md5 = (s) => createHash('md5').update(s, 'utf8').digest('hex')

const TAG = '$q$'
function quoted(value) {
  if (value === null) return 'null'
  if (String(value).includes(TAG)) {
    throw new Error(`A value contains ${TAG}, which is the quote tag. Change the tag.`)
  }
  return `${TAG}${value}${TAG}`
}

function asSql() {
  const values = rows
    .map((r) => '  (' + [
      quoted(r.scope), quoted(r.kind), quoted(r.name), quoted(r.subject),
      quoted(r.format), quoted(r.body), quoted(r.seed_key), quoted(r.audience), 'true',
    ].join(', ') + ')')
    .join(',\n')
  return [
    '-- The two affordability assessments, and their covering emails.',
    '-- Generated by scripts/letters/seed-affordability.mjs --sql. Do not edit by hand; edit',
    '-- affordability.mjs, run scripts/letters/build.mjs, and regenerate -- or the document in the',
    '-- database stops matching the one in the repository.',
    '-- Safe to run more than once. It removes nothing.',
    'begin;',
    'insert into public.message_templates',
    '  (scope, kind, name, subject, format, body, seed_key, audience, active)',
    'values',
    values,
    'on conflict (seed_key) do update set',
    '  scope = excluded.scope, kind = excluded.kind, name = excluded.name,',
    '  subject = excluded.subject, format = excluded.format, body = excluded.body,',
    '  audience = excluded.audience, active = excluded.active, updated_at = now();',
    '',
    '-- AND THE COVERING EMAIL POSTS THE FORM. Set here rather than in the insert because a row',
    '-- cannot point at an id it does not yet know. The pairing that matters is the AUDIENCE: a',
    "-- covering note written to a person that posts the company's form would ask a pensioner for",
    '-- management accounts.',
    ...['individual', 'company'].map((kind) => [
      'update public.message_templates e',
      '   set attachment_id = l.id',
      '  from public.message_templates l',
      ` where e.seed_key = 'email-affordability-${kind}'`,
      `   and l.seed_key = 'letter-affordability-${kind}';`,
    ].join('\n')),
    'commit;',
    '',
    '-- Read back what landed. A truncated form is worse than a missing one: a missing template',
    '-- cannot be chosen from a picker, and a truncated one can. Expect four rows, at these lengths:',
    ...rows.map((r) => `--   ${r.body.length} chars  ${r.name}`),
    'select name, length(body) as chars from public.message_templates',
    " where seed_key like '%affordability%' order by name;",
    '',
  ].join('\n')
}

if (process.argv.includes('--sql')) {
  process.stdout.write(asSql())
  process.exit(0)
}

const URL_BASE = process.env.SUPABASE_URL
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY
if (!URL_BASE || !KEY) {
  console.error('Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY, or pass --sql to write the SQL.')
  process.exit(1)
}

async function rest(path, init = {}) {
  const res = await fetch(`${URL_BASE}/rest/v1/${path}`, {
    ...init,
    headers: {
      apikey: KEY,
      authorization: `Bearer ${KEY}`,
      'content-type': 'application/json',
      ...(init.headers ?? {}),
    },
  })
  if (!res.ok) throw new Error(`${init.method ?? 'GET'} ${path}: ${res.status} ${await res.text()}`)
  return res.status === 204 ? null : res.json()
}

await rest('message_templates?on_conflict=seed_key', {
  method: 'POST',
  headers: { prefer: 'return=minimal,resolution=merge-duplicates' },
  body: JSON.stringify(rows),
})

const ids = Object.fromEntries(
  (await rest(`message_templates?seed_key=in.(${
    rows.map((r) => r.seed_key).join(',')})&select=id,seed_key,body`))
    .map((r) => [r.seed_key, r]),
)
for (const kind of ['individual', 'company']) {
  const letter = ids[`letter-affordability-${kind}`]
  const email = ids[`email-affordability-${kind}`]
  if (!letter || !email) continue
  await rest(`message_templates?seed_key=eq.email-affordability-${kind}`, {
    method: 'PATCH',
    headers: { prefer: 'return=minimal' },
    body: JSON.stringify({ attachment_id: letter.id }),
  })
}

let bad = 0
for (const want of rows) {
  const got = ids[want.seed_key]
  const ok = got && md5(got.body) === md5(want.body)
  if (!ok) bad += 1
  console.log(
    ok ? 'ok  ' : 'FAIL',
    want.name.padEnd(52),
    `${want.body.length} chars`,
    ok ? '' : `(stored ${got ? got.body.length : 'nothing'})`,
  )
}
console.log(bad === 0 ? '\nAll four rows verified.' : `\n${bad} row(s) did not match.`)
process.exit(bad === 0 ? 0 : 1)
